"""
Пассивный счётчик использования экранов (v2.132.0, этап 1 дорожной карты
из CLAUDE.md) — какие экраны бота реально открывают, чтобы позже (этап 4)
можно было убрать неиспользуемое. Опрашивать игроков бесполезно (проверено —
никто не отвечает), поэтому `UsageMiddleware` (bot/middleware.py) считает сам,
молча, без единого нового сообщения/кнопки для игроков.
"""
import re

_NUM_SEGMENT_RE = re.compile(r"_-?\d+")
_MAX_ACTION_LEN = 64


def normalize_action(raw: str) -> str:
    """Приводит callback_data/команду к устойчивому имени экрана.

    Числовые сегменты (id) вырезаются, чтобы player_profile_42 и
    player_profile_7 считались одним и тем же экраном: player_profile_42 ->
    player_profile, h2h_5_0 -> h2h, menu_stats остаётся без изменений (в нём
    нет числового сегмента). Команды — только имя команды, без аргументов:
    "/start ABC123" -> "/start"."""
    if raw.startswith("/"):
        action = raw.split(maxsplit=1)[0]
    else:
        action = _NUM_SEGMENT_RE.sub("", raw)
    return action[:_MAX_ACTION_LEN]


